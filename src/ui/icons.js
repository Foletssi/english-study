/* 填充式图形需要 `fill` 而非 `stroke`, 混用会让一个图标在 18px 下糊成一团 */
const FILLED = new Set(['play', 'starFilled']);

/**
 * 生成一个图标节点。
 * @param {keyof PATHS} name 图形名
 * @param {{ size?: number, class?: string, label?: string }} [options]
 *   `label` 给了就变成有语义的图标(带 role="img"), 不给就交给 `aria-hidden`
 *   —— 标签栏每一项下面已经有可见文字, 图标再说一遍会让读屏念两次。
 */
export function icon(name, { size = 20, class: className, label } = {}) {
  const path = PATHS[name];
  if (!path) throw new Error(`未知图标:${name}`);

  const filled = FILLED.has(name);
  const attrs = [
    `viewBox="${BOX}"`,
    `width="${size}"`,
    `height="${size}"`,
    `fill="${filled ? 'currentColor' : 'none'}"`,
    filled ? '' : 'stroke="currentColor"',
    filled ? '' : 'stroke-width="2"',
    filled ? '' : 'stroke-linecap="round"',
    filled ? '' : 'stroke-linejoin="round"',
    'focusable="false"',
    label ? `role="img" aria-label="${escaped(label)}"` : 'aria-hidden="true"',
    className ? `class="${escaped(className)}"` : '',
  ].filter(Boolean).join(' ');

  // `raw` 只接受代码自有字符串, 这里的两个插值是内部常量与 `size` 这个数字,
  // 没有任何一处来自用户或接口数据。
  return raw(`<svg xmlns="http://www.w3.org/2000/svg" ${attrs}><path d="${path}"/></svg>`);
}

function escaped(value) {
  return String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');
}

